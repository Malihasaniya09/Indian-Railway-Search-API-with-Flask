# Reverse mapping: station to city
STATION_TO_CITY = {}
for city, stations in CITY_STATIONS.items():
    for station in stations:
        STATION_TO_CITY[station.lower()] = city

def get_city_from_station(station: str) -> str:
    """Get the city name from any station name"""
    station_lower = station.lower().strip()
    
    # If it's already a city name
    if station in CITY_STATIONS:
        return station
    
    # Look up in station to city mapping
    city = STATION_TO_CITY.get(station_lower)
    if city:
        return city
    
    # If not found, return the original (might be a standalone station)
    return station

def get_all_stations_for_city(city_or_station: str) -> list:
    """Get all stations for a given city or station name"""
    city = get_city_from_station(city_or_station)
    return CITY_STATIONS.get(city, [city_or_station])

# Reverse mapping: Code to Name
CODE_TO_STATION = {v: k for k, v in STATION_CODES.items()}

def get_station_code(station_name: str) -> str:
    """
    Get station code from station name
    Returns the name itself if code not found
    """
    return STATION_CODES.get(station_name, station_name)

def get_station_name(station_code: str) -> str:
    """
    Get station name from station code
    Returns the code itself if name not found
    """
    return CODE_TO_STATION.get(station_code.upper(), station_code)

def search_stations(query: str) -> list:
    """
    Search for stations matching the query
    """
    query = query.lower()
    results = []
    for name, code in STATION_CODES.items():
        if query in name.lower() or query in code.lower():
            results.append({"name": name, "code": code})
    return results

# Get all station names for dropdown
def get_all_stations() -> list:
    """
    Get list of all station names
    """
    return sorted(list(set(STATION_CODES.keys())))

